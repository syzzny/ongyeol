/** "2026-07-14" → "2026.07.14" */
export function formatDate(date: string) {
  return date.replaceAll("-", ".");
}

/** 주소의 이름으로 글 찾기 (없으면 null). 앞뒤 글도 함께 돌려줌 */
export function findNews(slug: string) {
  const index = NEWS.findIndex((item) => item.slug === slug);
  if (index === -1) return null;

  return {
    item: NEWS[index],
    prev: NEWS[index - 1] ?? null, // 이전 글 = 더 최신 글
    next: NEWS[index + 1] ?? null, // 다음 글 = 더 예전 글
  };
}